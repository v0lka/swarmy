"""``EvidenceRecorder`` — session evidence files and Evidence records (arch §6.2, T2.2.4).

One completed platform HTTP call produces one evidence unit: the folder
``evidence/<request_id>/`` (``request_id`` is the uuid4 correlation id of the
call) holding ``request.txt`` and — for ``evidence_depth="request_response"``
— ``response.txt``. The files are **raw, byte-for-byte** the traffic the
client exchanged (D21: session files stay raw; only the model-bound preview
is sanitized), except that a body exceeding the session ``max_body_bytes``
threshold is cut at the threshold and closed with a truncation-marker line —
the full content of the *kept* prefix stays byte-exact.

The recorder owns no memory SQL itself (arch invariant 3: domain tables are
written only through ``MemoryStore``): it creates the ``Evidence`` pointer
row through the injected store, typed structurally as :class:`EvidenceStore`
so the wiring can pass the real ``MemoryStore`` without a package coupling
(``tools.*`` imports memory *models*, never the store module, arch §2.5).

Only ``kind="http_request_response"`` is produced in v0.1 — the other
``EvidenceKind`` values are reserved and never written here (D20).
"""

from __future__ import annotations

from datetime import UTC, datetime
from typing import TYPE_CHECKING, Final, Protocol

from swarmy.memory.models import Evidence, EvidenceDraft, EvidenceKind
from swarmy.tools.projector import truncation_marker

if TYPE_CHECKING:
    from pathlib import Path

#: The single evidence kind v0.1 produces (D20: screenshot/har/grpc_file are
#: reserved and never generated by this recorder).
PRODUCED_KIND: Final[EvidenceKind] = EvidenceKind.HTTP_REQUEST_RESPONSE

#: Directory name inside the session folder holding the evidence units
#: (arch §3.3 session layout).
EVIDENCE_DIRNAME: Final[str] = "evidence"


class EvidenceStore(Protocol):
    """Structural type of the memory slice the recorder needs (arch §2.5).

    The session ``MemoryStore`` satisfies it once it exposes
    ``add_evidence``; tests may pass a lightweight double.
    """

    async def add_evidence(self, draft: EvidenceDraft) -> Evidence:
        """Insert one evidence pointer row and return it with its id."""
        ...


class EvidenceRecorder:
    """Writes raw request/response files and the ``Evidence`` pointer row.

    One instance per session, injected into :class:`SwarmyHttpClient` (the
    client calls :meth:`record` once per completed call, after the pipeline
    and limiter stages allowed it — a blocked call leaves no evidence).
    """

    __slots__ = ("_evidence_dir", "_max_body_bytes", "_store")

    def __init__(self, *, evidence_dir: Path, store: EvidenceStore, max_body_bytes: int) -> None:
        """Bind the session evidence folder, the store and the body threshold.

        Args:
            evidence_dir: the session ``evidence/`` directory (created
                lazily on first record; unit folders below it).
            store: the memory store receiving the ``Evidence`` pointer rows.
            max_body_bytes: the session body threshold (``limits`` of
                arch §6.4); bodies are cut here with a truncation marker.
        """
        self._evidence_dir = evidence_dir
        self._max_body_bytes = max_body_bytes
        self._store = store

    async def record(
        self,
        *,
        request_head: bytes,
        request_body: bytes,
        tool: str,
        correlation_id: str,
        request_id: str,
        include_response: bool,
        response_head: bytes = b"",
        response_body: bytes = b"",
        response_truncated: bool = False,
        response_dropped_bytes: int | None = None,
    ) -> Evidence:
        """Persist one evidence unit and create its ``Evidence`` record.

        Args:
            request_head: the raw request head (request line + headers,
                without the empty separator line; the recorder appends it).
            request_body: the raw request body exactly as sent.
            tool: name of the platform tool that made the call (metadata).
            correlation_id: the session correlation id of the call (metadata).
            request_id: the uuid4 correlation id of the call — names the
                evidence folder and ties the files to the ``ResponseRecord``.
            include_response: ``True`` for ``evidence_depth=
                "request_response"`` — also writes ``response.txt``;
                ``False`` for depth ``"request"`` (D20 depth semantics).
            response_head: the raw response head (status line + headers);
                ignored when ``include_response`` is ``False``.
            response_body: the raw response body as read from the wire
                (already capped by the client's reader); ignored when
                ``include_response`` is ``False``.
            response_truncated: whether the client's reader stopped at the
                session body limit (arch §6.4) before reading the whole
                body; closes ``response.txt`` with a truncation marker.
            response_dropped_bytes: exact count of the unread remainder when
                the target declared ``Content-Length``; ``None`` when the
                total size is unknown (streaming bodies are not pulled just
                to be counted).

        Returns:
            The created ``Evidence`` record — its ``id`` becomes the
            ``ResponseRecord.evidence_id`` of the call.
        """
        unit_dir = self._evidence_dir / request_id
        unit_dir.mkdir(parents=True, exist_ok=True)
        request_path = unit_dir / "request.txt"
        request_path.write_bytes(request_head + b"\r\n" + _capped(request_body, self._max_body_bytes))
        paths = [self._relative(request_path)]
        if include_response:
            response_path = unit_dir / "response.txt"
            body = _capped(response_body, self._max_body_bytes)
            if response_truncated:
                body += _truncated_note(response_dropped_bytes, self._max_body_bytes)
            response_path.write_bytes(response_head + b"\r\n" + body)
            paths.append(self._relative(response_path))
        metadata = {
            "ts": datetime.now(UTC).isoformat(),
            "tool": tool,
            "correlation_id": correlation_id,
            "request_id": request_id,
        }
        return await self._store.add_evidence(
            EvidenceDraft(
                kind=PRODUCED_KIND,  # D20: the only kind produced in v0.1
                session_paths=paths,
                metadata=metadata,
            )
        )

    def _relative(self, path: Path) -> str:
        """Session-relative, POSIX-style path of one evidence file (arch §4.2)."""
        return path.relative_to(self._evidence_dir.parent).as_posix()


def _capped(body: bytes, max_body_bytes: int) -> bytes:
    """Cut ``body`` at the threshold, closing with the §6.8 truncation marker.

    Up to the threshold the bytes pass through unchanged (byte-exact AC);
    beyond it the kept prefix stays and one marker line records how many
    bytes the session budget dropped.
    """
    if len(body) <= max_body_bytes:
        return body
    dropped = len(body) - max_body_bytes
    marker = f"\n{truncation_marker(dropped)}\n".encode()
    return body[:max_body_bytes] + marker


def _truncated_note(dropped: int | None, limit: int) -> bytes:
    """Closing marker line for a response body the §6.4 read cutoff shortened.

    The canonical ``[truncated N bytes]`` form is used when the dropped count
    is known (declared ``Content-Length``); otherwise the marker states the
    limit explicitly — the client's reader stops at the threshold by design
    and never pulls the remainder just to count it.
    """
    if dropped is not None:
        return f"\n{truncation_marker(dropped)}\n".encode()
    return (
        f"\n[truncated: body exceeded the session limit of {limit} bytes; "
        f"the remainder was not read]\n"
    ).encode()


